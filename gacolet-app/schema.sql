CREATE TABLE IF NOT EXISTS clients (
  id INT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(12) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  formula VARCHAR(120) NOT NULL DEFAULT '',
  modules VARCHAR(20) NOT NULL DEFAULT 'com',
  metricool_blog_id VARCHAR(20) NOT NULL DEFAULT '',
  contacts_goal INT NOT NULL DEFAULT 0,
  qualified_definition TEXT,
  drive_url VARCHAR(500) NOT NULL DEFAULT '',
  active INT NOT NULL DEFAULT 1,
  created_at VARCHAR(30) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  prenom VARCHAR(80) NOT NULL,
  nom VARCHAR(80) NOT NULL,
  entreprise VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL,
  tel VARCHAR(40) NOT NULL DEFAULT '',
  activite TEXT,
  zone TEXT,
  reseaux TEXT,
  objectif VARCHAR(120) NOT NULL DEFAULT '',
  clientele TEXT,
  dispo TEXT,
  token VARCHAR(64) NOT NULL UNIQUE,
  created_at VARCHAR(30) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS decisions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  post_id VARCHAR(40) NOT NULL,
  post_title VARCHAR(200) NOT NULL DEFAULT '',
  post_date VARCHAR(30) NOT NULL DEFAULT '',
  status VARCHAR(10) NOT NULL,
  note TEXT,
  user_id INT NOT NULL,
  created_at VARCHAR(30) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS requests (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  user_id INT NOT NULL,
  type VARCHAR(60) NOT NULL,
  message TEXT NOT NULL,
  files TEXT,
  status VARCHAR(30) NOT NULL DEFAULT 'Envoyée',
  created_at VARCHAR(30) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS leads (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  date VARCHAR(10) NOT NULL,
  title VARCHAR(200) NOT NULL,
  detail TEXT,
  qualified INT,
  qualified_by INT,
  qualified_at VARCHAR(30),
  created_at VARCHAR(30) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS events (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  date VARCHAR(10) NOT NULL,
  kind VARCHAR(20) NOT NULL DEFAULT '',
  title VARCHAR(200) NOT NULL,
  detail VARCHAR(300) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS deliverables (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  date VARCHAR(10) NOT NULL,
  title VARCHAR(200) NOT NULL,
  detail VARCHAR(300) NOT NULL DEFAULT '',
  url VARCHAR(500) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS stats (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  period VARCHAR(7) NOT NULL,
  module VARCHAR(10) NOT NULL,
  data TEXT NOT NULL,
  source VARCHAR(300) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS docs (
  col VARCHAR(40) NOT NULL,
  id VARCHAR(120) NOT NULL,
  data MEDIUMTEXT NOT NULL,
  deleted INT NOT NULL DEFAULT 0,
  updated_at VARCHAR(30) NOT NULL,
  PRIMARY KEY (col, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE INDEX IF NOT EXISTS docs_updated ON docs (updated_at)
